#!/usr/bin/env python3
"""Render talklee.conf and pg_hba.conf for the dedicated Talklee database host.

Stdlib only, no secrets involved. Defaults are fail-closed: private listen
address, TLS-only client access, scram-sha-256, explicit CIDR allow-list.
"""
from __future__ import annotations

import argparse
import ipaddress
from pathlib import Path
import re
import sys

NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,62}$")


class ConfigError(ValueError):
    pass


def conf_path(value, label):
    text = str(value).replace("\\", "/")
    if not text or any(c in text for c in "'\"\n\r\0"):
        raise ConfigError(f"{label}: path must be non-empty and contain no quotes or newlines")
    return text


def archive_dir(value):
    text = str(value).replace("\\", "/")
    if not text or any(c in text for c in "'\"`$%\\ \t\n\r\0;&|<>()"):
        raise ConfigError("wal-archive-dir: no quotes, spaces, newlines, '%' or shell metacharacters allowed")
    if not text.startswith("/") and not re.match(r"^[A-Za-z]:/", text):
        raise ConfigError("wal-archive-dir: must be an absolute path")
    return text.rstrip("/") or "/"


def listen_addresses(values, allow_public):
    result = []
    for raw in values:
        for item in str(raw).split(","):
            item = item.strip()
            if item in ("*", "") and not allow_public:
                raise ConfigError("listen-address: '*' / empty refused (use --i-understand-public-listen)")
            if item == "*":
                result.append(item)
                continue
            try:
                ip = ipaddress.ip_address(item)
            except ValueError:
                raise ConfigError(f"listen-address: {item!r} is not an IP address") from None
            if ip.is_unspecified and not allow_public:
                raise ConfigError(f"listen-address: {item} listens on every interface (use --i-understand-public-listen)")
            result.append(str(ip))
    if not result:
        raise ConfigError("listen-address: at least one address required")
    return result


def allow_networks(values, allow_public):
    result = []
    for raw in values:
        try:
            net = ipaddress.ip_network(str(raw).strip(), strict=True)
        except ValueError as exc:
            raise ConfigError(f"allow: invalid CIDR {raw!r}: {exc}") from None
        if net.prefixlen == 0 and not allow_public:
            raise ConfigError(f"allow: {net} is the whole internet (use --i-understand-public-allow)")
        result.append(net)
    if not result:
        raise ConfigError("allow: at least one CIDR required")
    return result


def tuning(memory_mb):
    if memory_mb < 512:
        raise ConfigError("memory-mb: at least 512 required")
    return {
        "shared_buffers": f"{memory_mb // 4}MB",
        "effective_cache_size": f"{memory_mb * 3 // 4}MB",
        "work_mem": f"{max(4, min(64, memory_mb // 192))}MB",
        "maintenance_work_mem": f"{max(64, min(2048, memory_mb // 12))}MB",
    }


def render_conf(listen, port, cert, key, ca, memory_mb, wal_dir):
    lines = ["# Generated by render_config.py - do not edit by hand; re-render instead.",
             "listen_addresses = '" + ",".join(listen) + "'",
             f"port = {int(port)}",
             "ssl = on",
             f"ssl_cert_file = '{cert}'",
             f"ssl_key_file = '{key}'"]
    if ca:
        lines.append(f"ssl_ca_file = '{ca}'")
    lines += ["ssl_min_protocol_version = 'TLSv1.2'",
              "password_encryption = 'scram-sha-256'"]
    lines += [f"{k} = {v}" for k, v in tuning(memory_mb).items()]
    lines += ["random_page_cost = 1.1", "wal_compression = on",
              "idle_in_transaction_session_timeout = 300s",
              "log_min_duration_statement = 500", "log_lock_waits = on",
              "log_connections = on", "log_disconnections = on"]
    if wal_dir:
        lines += ["wal_level = replica", "archive_mode = on", "archive_timeout = 60",
                  f"archive_command = 'test ! -f {wal_dir}/%f && cp %p {wal_dir}/%f.tmp && mv {wal_dir}/%f.tmp {wal_dir}/%f'"]
    return "\n".join(lines) + "\n"


def render_hba(database, networks, admin_local_peer, allow_replication,
               admin_role=None, replication_role="talklee_replication"):
    lines = ["# Generated by render_config.py. TLS only, scram-sha-256 only."]
    if admin_local_peer:
        lines.append("local   all             postgres                                peer")
    lines += ["hostnossl all             all             0.0.0.0/0               reject",
              "hostnossl all             all             ::/0                    reject"]
    for net in networks:
        lines.append(f"hostssl {database:<15} all             {str(net):<23} scram-sha-256")
    # The cut-over/restore administrator works from the maintenance database
    # (CREATE DATABASE, roles); nobody else may connect to it.
    if admin_role:
        for net in networks:
            lines.append(f"hostssl postgres        {admin_role:<15} {str(net):<23} scram-sha-256")
    if allow_replication:
        for net in networks:
            lines.append(f"hostssl replication     {replication_role:<15} {str(net):<23} scram-sha-256")
    lines += ["host    all             all             0.0.0.0/0               reject",
              "host    all             all             ::/0                    reject"]
    return "\n".join(lines) + "\n"


def render(args):
    if not NAME.match(args.database):
        raise ConfigError("database: must match [A-Za-z_][A-Za-z0-9_]*")
    if not 1 <= args.port <= 65535:
        raise ConfigError("port out of range")
    listen = listen_addresses(args.listen_address, args.i_understand_public_listen)
    nets = allow_networks(args.allow, args.i_understand_public_allow)
    conf = render_conf(listen, args.port, conf_path(args.ssl_cert_file, "ssl-cert-file"),
                       conf_path(args.ssl_key_file, "ssl-key-file"),
                       conf_path(args.ssl_ca_file, "ssl-ca-file") if args.ssl_ca_file else None,
                       args.memory_mb, archive_dir(args.wal_archive_dir) if args.wal_archive_dir else None)
    for role in (args.admin_role, args.replication_role):
        if role is not None and not NAME.match(role):
            raise ConfigError("role names must match [A-Za-z_][A-Za-z0-9_]*")
    hba = render_hba(args.database, nets, args.admin_local_peer, args.allow_replication,
                     args.admin_role, args.replication_role)
    return conf, hba, listen, nets


def parser():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--listen-address", action="append", required=True)
    p.add_argument("--allow", action="append", required=True, help="client CIDR; repeatable")
    p.add_argument("--ssl-cert-file", required=True)
    p.add_argument("--ssl-key-file", required=True)
    p.add_argument("--ssl-ca-file")
    p.add_argument("--database", required=True)
    p.add_argument("--out-dir", type=Path, required=True)
    p.add_argument("--wal-archive-dir")
    p.add_argument("--memory-mb", type=int, default=4096)
    p.add_argument("--port", type=int, default=5432)
    p.add_argument("--admin-local-peer", action="store_true")
    p.add_argument("--allow-replication", action="store_true")
    p.add_argument("--replication-role", default="talklee_replication", help="base-backup role (pitr.py)")
    p.add_argument("--admin-role", help="administrator allowed into the postgres maintenance database")
    p.add_argument("--force", action="store_true")
    p.add_argument("--i-understand-public-listen", action="store_true")
    p.add_argument("--i-understand-public-allow", action="store_true")
    return p


def main(argv=None):
    args = parser().parse_args(argv)
    try:
        conf, hba, listen, nets = render(args)
        out = args.out_dir
        targets = [out / "talklee.conf", out / "pg_hba.conf"]
        existing = [str(t) for t in targets if t.exists()]
        if existing and not args.force:
            raise ConfigError("refusing to overwrite (use --force): " + ", ".join(existing))
        out.mkdir(parents=True, exist_ok=True)
        for target, text in zip(targets, (conf, hba)):
            target.write_text(text, encoding="utf-8", newline="\n")
    except ConfigError as exc:
        print("render_config: " + str(exc), file=sys.stderr)
        return 2
    print(f"rendered {targets[0]} and {targets[1]}")
    print(f"  listen={','.join(listen)} port={args.port} tls=on(min TLSv1.2) auth=scram-sha-256")
    print(f"  allow={','.join(map(str, nets))} database={args.database} "
          f"wal_archive={'on' if args.wal_archive_dir else 'off'} replication={'on' if args.allow_replication else 'off'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
