#!/usr/bin/env python3
"""Render empty environment inventories without constructing application settings.

Only Python source, Compose source and existing .env.example templates are read.
Default mode prints a template; --write replaces only the two example files.
Static legacy reads are supplemental evidence, not a proof about dynamic names.
"""
from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.core.config import Settings


_NAME = re.compile(r"[A-Z_][A-Z0-9_]*\Z")
_COMPOSE_NAME = re.compile(r"(?<!\$)\$\{([A-Z_][A-Z0-9_]*)(?=[:}?+\-])")
_TEMPLATES = (Path(".env.example"), Path("backend/.env.example"))


def settings_env_names(settings_class=Settings) -> list[str]:
    """Accepted flat environment names from field metadata, never field values."""
    names = set()
    prefix = settings_class.model_config.get("env_prefix", "")
    for name, field in settings_class.model_fields.items():
        alias = field.validation_alias or field.alias
        candidates = getattr(alias, "choices", None) or ([alias] if alias else [prefix + name])
        for candidate in candidates:
            if not isinstance(candidate, str) or not _NAME.fullmatch(candidate.upper()):
                raise ValueError("Unsupported environment field alias")
            names.add(candidate.upper())
    return sorted(names)


def render_template(settings_class=Settings, *, legacy_names=(), compose_names=()) -> str:
    model_names = set(settings_env_names(settings_class))
    supplemental = set(legacy_names) | set(compose_names)
    if any(not isinstance(name, str) or not _NAME.fullmatch(name) for name in supplemental):
        raise ValueError("Invalid supplemental environment name")
    lines = [
        "# Generated by backend/scripts/generate_env_example.py; do not edit by hand.",
        "# Every value is intentionally empty. This inventory is not a production config.",
        "# Fill only the values needed for your deployment in a private configuration.",
        "# Never copy values from a real .env into this file.",
        "# Root Compose and backend processes have different consumers; see",
        "# backend/docs/environment_templates.md before configuring either.",
        "", "# Settings model (accepted environment aliases)",
    ]
    lines.extend(f"{name}=" for name in sorted(model_names))
    lines.extend(["", "# Supplemental static legacy Python / root Compose names",
                  "# Not validated by Settings merely because they appear here."])
    lines.extend(f"{name}=" for name in sorted(supplemental - model_names))
    return "\n".join(lines) + "\n"


def legacy_inventory(source_root: Path) -> dict:
    """List literal os.getenv/environ reads and locations of dynamic keys.

    Imports and their aliases are recognized statically. Modules are never
    imported or evaluated, and defaults/values are never included in output.
    """
    names: dict[str, list[str]] = {}
    dynamic = []
    for path in sorted(source_root.rglob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8-sig"), filename=str(path))
        os_names, getenv_names, environ_names = set(), set(), set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                os_names.update(alias.asname or "os" for alias in node.names if alias.name == "os")
            elif isinstance(node, ast.ImportFrom) and node.module == "os":
                for alias in node.names:
                    if alias.name == "getenv":
                        getenv_names.add(alias.asname or alias.name)
                    elif alias.name == "environ":
                        environ_names.add(alias.asname or alias.name)

        def is_os(node):
            return isinstance(node, ast.Name) and node.id in os_names

        def is_environ(node):
            return ((isinstance(node, ast.Name) and node.id in environ_names)
                    or (isinstance(node, ast.Attribute) and node.attr == "environ" and is_os(node.value)))

        def record(node, key):
            location = f"{path.relative_to(source_root).as_posix()}:{node.lineno}"
            if isinstance(key, ast.Constant) and isinstance(key.value, str) and _NAME.fullmatch(key.value):
                names.setdefault(key.value, []).append(location)
            else:
                dynamic.append(location)

        for node in ast.walk(tree):
            if isinstance(node, ast.Call):
                function = node.func
                recognized = (
                    isinstance(function, ast.Name) and function.id in getenv_names
                ) or (
                    isinstance(function, ast.Attribute)
                    and ((function.attr == "getenv" and is_os(function.value))
                         or (function.attr in {"get", "setdefault"} and is_environ(function.value)))
                )
                if recognized:
                    key = node.args[0] if node.args else next(
                        (keyword.value for keyword in node.keywords if keyword.arg == "key"), None
                    )
                    record(node, key)
            elif isinstance(node, ast.Subscript) and isinstance(node.ctx, ast.Load) and is_environ(node.value):
                record(node, node.slice)
    return {"names": {name: sorted(set(locations)) for name, locations in sorted(names.items())},
            "dynamic_reads": sorted(set(dynamic))}


def _inventory(root: Path) -> dict:
    # The scope is explicit: application Python plus the root Compose profile.
    # Deployment shells, native providers and dynamic configuration are not
    # silently certified by this source-only inventory.
    report = legacy_inventory(root / "backend/app")
    compose_path = root / "docker-compose.yml"
    report["compose_names"] = sorted(set(_COMPOSE_NAME.findall(
        compose_path.read_text(encoding="utf-8") if compose_path.is_file() else ""
    )))
    return report


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="Replace only the two .env.example templates")
    mode.add_argument("--check", action="store_true", help="Fail if either template is absent or stale")
    mode.add_argument("--inventory", action="store_true", help="Print supplemental names/locations as JSON")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        if not (root / "backend/app").is_dir():
            raise ValueError("Application source directory is missing")
        report = _inventory(root)
        if args.inventory:
            print(json.dumps(report, indent=2, sort_keys=True))
            return 0
        content = render_template(Settings, legacy_names=report["names"], compose_names=report["compose_names"])
        targets = [root / path for path in _TEMPLATES]
        if any(path.is_symlink() or not path.resolve().is_relative_to(root) for path in targets):
            raise ValueError("Example templates must be regular files inside the selected repository")
        if args.write:
            for relative, target in zip(_TEMPLATES, targets):
                target.write_text(content, encoding="utf-8", newline="\n")
                print(f"Wrote {relative.as_posix()}")
        elif args.check:
            stale = [relative.as_posix() for relative, target in zip(_TEMPLATES, targets)
                     if not target.is_file() or target.read_text(encoding="utf-8") != content]
            if stale:
                print("Stale environment examples: " + ", ".join(stale), file=sys.stderr)
                return 1
            print("Environment examples match Settings and the supplemental static inventory.")
        else:
            print(content, end="")
        return 0
    except (OSError, SyntaxError, ValueError) as exc:
        # Source and private runtime values never appear in diagnostics.
        print(f"Environment inventory failed ({type(exc).__name__}).", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
